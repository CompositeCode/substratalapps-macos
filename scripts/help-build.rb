#!/usr/bin/env ruby
# frozen_string_literal: true

# Versioned build of the Help Center. Run by .github/workflows/help.yml on every
# push to main that touches the app or the help site, and runnable locally the
# same way. Adapted from the API repository's scripts/docs-build.rb, so both
# sites version the same way.
#
#   scripts/help-build.rb --archive DIR --out DIR [--bump patch|minor|major]
#                         [--commit SHA] [--summary TEXT] [--released YYYY-MM-DD]
#
# --archive is a checkout of the `help-versions` branch (an empty dir is fine for
# the first build): manifest.yml plus one frozen static build per version.
#
# Each run:
#   1. Generates the app-derived pages (scripts/help-generate.rb).
#   2. Picks the next docs version (1.0.0 for an empty archive, else bumped).
#   3. Writes help/_data/versions.yml for the header badge and Versions page;
#      each entry records the app version and Platform API version it describes.
#   4. Builds this version as a frozen snapshot at <archive>/<v>/.
#   5. Builds the live site into --out with every snapshot under /versions/<v>/.
#
# Committing the archive back and deploying --out are the workflow's job.

require "date"
require "fileutils"
require "optparse"
require "tmpdir"
require "yaml"

ROOT = File.expand_path("..", __dir__)
HELP = File.join(ROOT, "help")
DATA_FILE = File.join(HELP, "_data", "versions.yml")
BUMPS = %w[patch minor major].freeze

def abort_with(msg)
  warn "help-build: #{msg}"
  exit 1
end

opts = { bump: "patch", released: Date.today.iso8601 }
OptionParser.new do |o|
  o.on("--archive DIR") { |v| opts[:archive] = File.expand_path(v) }
  o.on("--out DIR") { |v| opts[:out] = File.expand_path(v) }
  o.on("--bump LEVEL", BUMPS) { |v| opts[:bump] = v }
  o.on("--commit SHA") { |v| opts[:commit] = v }
  o.on("--summary TEXT") { |v| opts[:summary] = v }
  o.on("--released DATE") { |v| opts[:released] = v }
end.parse!
abort_with "--archive and --out are required" unless opts[:archive] && opts[:out]

generate = [File.join(ROOT, "scripts", "help-generate.rb")]
generate += ["--commit", opts[:commit]] if opts[:commit]
system("ruby", *generate) || abort_with("help-generate failed")
build = YAML.safe_load(File.read(File.join(HELP, "_data", "build.yml")))

def next_version(latest, bump)
  return "1.0.0" unless latest

  major, minor, patch = latest.split(".").map(&:to_i)
  case bump
  when "major" then "#{major + 1}.0.0"
  when "minor" then "#{major}.#{minor + 1}.0"
  else "#{major}.#{minor}.#{patch + 1}"
  end
end

def jekyll_build(dest, overlay = nil)
  configs = ["_config.yml", overlay].compact.join(",")
  Dir.chdir(HELP) do
    ok = system("bundle", "exec", "jekyll", "build", "--config", configs, "--destination", dest)
    abort_with "jekyll build failed (#{dest})" unless ok
  end
end

FileUtils.mkdir_p(opts[:archive])
manifest_path = File.join(opts[:archive], "manifest.yml")
manifest = File.exist?(manifest_path) ? (YAML.safe_load(File.read(manifest_path)) || {}) : {}
versions = manifest["versions"] || []
versions.sort_by! { |v| Gem::Version.new(v["version"]) }.reverse!

version = next_version(versions.first&.fetch("version"), opts[:bump])
abort_with "#{opts[:archive]}/#{version} already exists" if File.exist?(File.join(opts[:archive], version))

current = {
  "version" => version,
  "released" => opts[:released],
  "app_version" => build["app_version"],
  "api_spec_version" => build["api_spec_version"],
  "api_header_version" => build["api_header_version"],
}
current["commit"] = opts[:commit] if opts[:commit]
current["summary"] = opts[:summary].lines.first.strip if opts[:summary] && !opts[:summary].strip.empty?

File.write(DATA_FILE, <<~HEAD + { "current" => current, "archive" => versions }.to_yaml.sub(/\A---\n/, ""))
  # GENERATED by scripts/help-build.rb on every GitHub build. Not committed.
  # The real history lives on the help-versions branch (manifest.yml).
HEAD
puts "help-build: building v#{version} (#{opts[:bump]} bump from #{versions.first&.fetch('version') || 'nothing'}); " \
     "app #{build['app_version']}, API #{build['api_spec_version']}"

config = YAML.safe_load(File.read(File.join(HELP, "_config.yml")))

Dir.mktmpdir("help-build-") do |tmp|
  overlay = File.join(tmp, "_config.archive.yml")
  snapshot = File.join(tmp, "snapshot")
  File.write(overlay, {
    "baseurl" => "#{config.fetch('baseurl')}/versions/#{version}",
    "version_archive_build" => true,
    "exclude" => (config["exclude"] || []) + ["versions"],
  }.to_yaml)
  jekyll_build(snapshot, overlay)
  %w[robots.txt sitemap.xml 404.html].each { |f| FileUtils.rm_f(File.join(snapshot, f)) }
  FileUtils.cp_r(snapshot, File.join(opts[:archive], version))
end

versions.unshift(current)
File.write(manifest_path, <<~HEAD + { "versions" => versions }.to_yaml.sub(/\A---\n/, ""))
  # Every released version of the Help Center, newest first. Written by
  # scripts/help-build.rb on main's GitHub build; each entry has a frozen
  # static copy at <version>/ on this branch, served at /versions/<version>/.
HEAD

FileUtils.rm_rf(opts[:out])
jekyll_build(opts[:out])
versions.each do |v|
  src = File.join(opts[:archive], v["version"])
  abort_with "manifest lists v#{v['version']} but #{src} is missing" unless File.directory?(src)
  FileUtils.mkdir_p(File.join(opts[:out], "versions"))
  FileUtils.cp_r(src, File.join(opts[:out], "versions", v["version"]))
end

system("ruby", File.join(ROOT, "scripts", "help-check.rb"), opts[:out]) || abort_with("help-check failed")

File.write(ENV["GITHUB_OUTPUT"], "version=#{version}\n", mode: "a") if ENV["GITHUB_OUTPUT"]
puts "help-build: v#{version} built into #{opts[:out]} with #{versions.size} archived version(s)"
