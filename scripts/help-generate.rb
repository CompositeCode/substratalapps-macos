#!/usr/bin/env ruby
# frozen_string_literal: true

# Generates the parts of the Help Center that come from the app itself, so the
# docs can't drift from the code. Run before every help build (help-build.rb
# and the CI workflows do), and locally before `jekyll serve`.
#
#   scripts/help-generate.rb [--commit SHA]
#
# Reads:
#   Packages/SubstratalKit/Sources/SubstratalKit/Resources/screens.json  the screen catalog the app navigates with
#   App/Screens/ScreenHost.swift                                          which screens are built (vs. placeholders)
#   help/api/openapi.yaml                                                 the Platform API contract (scripts/sync-openapi.sh)
#   project.yml                                                           the app version
#   CHANGELOG.md                                                          release notes
#   help/_screen-notes/<ID>.md                                            optional hand-written notes per screen
#
# Writes (all gitignored):
#   help/_data/screens.json, help/_data/build.yml
#   help/screens/<domain>.md and help/screens/<id>.md   one page per domain and per screen
#   help/release-notes.md

require "date"
require "json"
require "set"
require "optparse"
require "yaml"
require "fileutils"

ROOT = File.expand_path("..", __dir__)
HELP = File.join(ROOT, "help")
CATALOG = File.join(ROOT, "Packages/SubstratalKit/Sources/SubstratalKit/Resources/screens.json")
HOST = File.join(ROOT, "App/Screens/ScreenHost.swift")
OPENAPI = File.join(HELP, "api", "openapi.yaml")

opts = {}
OptionParser.new { |o| o.on("--commit SHA") { |v| opts[:commit] = v } }.parse!

def slug(text) = text.downcase.gsub(/[^a-z0-9]+/, "-").gsub(/\A-|-\z/, "")

def yaml_string(value) = value.to_s.to_json # JSON strings are valid YAML scalars

catalog = JSON.parse(File.read(CATALOG))
screens = catalog.fetch("screens")
built = File.read(HOST).scan(/case "([A-Z]+-\d+)"/).flatten.to_set

# ── Build metadata ──────────────────────────────────────────────────────────
spec = YAML.safe_load(File.read(OPENAPI), permitted_classes: [Date, Time], aliases: true)
header_versions = spec.dig("components", "parameters", "ApiVersion", "schema", "enum") || []
operations = spec.fetch("paths").sum { |_, item| item.keys.count { |k| %w[get post put patch delete].include?(k) } }
project = YAML.safe_load(File.read(File.join(ROOT, "project.yml")))
build = {
  "app_version" => project.dig("settings", "base", "MARKETING_VERSION").to_s,
  "api_spec_version" => spec.dig("info", "version").to_s,
  "api_header_versions" => header_versions.map(&:to_s),
  "api_header_version" => header_versions.map(&:to_s).max_by(&:to_i),
  "api_operations" => operations,
  "api_base_url" => spec.fetch("servers").first.fetch("url"),
  "screens_total" => screens.size,
  "screens_built" => built.size,
  "built_screens" => built.to_a.sort,
  "ui_spec" => catalog["spec"],
  "commit" => opts[:commit],
}.compact
FileUtils.mkdir_p(File.join(HELP, "_data"))
File.write(File.join(HELP, "_data", "build.yml"), "# GENERATED by scripts/help-generate.rb. Not committed.\n" + build.to_yaml.sub(/\A---\n/, ""))
FileUtils.cp(CATALOG, File.join(HELP, "_data", "screens.json"))

# ── Screen reference ────────────────────────────────────────────────────────
dir = File.join(HELP, "screens")
Dir.glob(File.join(dir, "*.md")).each { |f| File.delete(f) unless File.basename(f) == "index.md" }

SECTION_TITLES = { "personal" => "Personal", "administration" => "Administration", "developer" => "Developer" }.freeze
KEY_GLYPHS = { "cmd" => "⌘", "opt" => "⌥", "ctrl" => "⌃", "shift" => "⇧" }.freeze

def shortcut_glyphs(spec)
  return nil unless spec

  parts = spec.split("+")
  key = parts.pop
  parts.sort_by { |p| %w[ctrl opt shift cmd].index(p) }.map { |p| KEY_GLYPHS.fetch(p) }.join + key.upcase
end

domains = screens.group_by { |s| s["domain"] }
domains.each_with_index do |(domain, members), index|
  code, name = domain.split(" ", 2)
  File.write(File.join(dir, "#{slug(domain)}.md"), <<~MD)
    ---
    layout: default
    title: #{yaml_string(name)}
    parent: Screen Reference
    nav_order: #{index + 1}
    has_children: true
    permalink: /screens/#{slug(domain)}/
    ---

    # #{name}
    {: .no_toc }

    Domain #{code} · #{members.size} screens · #{members.count { |s| built.include?(s["id"]) }} built
    {: .fs-5 .fw-300 }

    | Screen | What it's for | Status |
    |---|---|---|
    #{members.map { |s| "| [#{s['id']} #{s['title']}](#{'{{'} '/screens/#{s['id'].downcase}/' | relative_url #{'}}'}) | #{s['purpose'].gsub('|', '\\|')} | #{built.include?(s['id']) ? 'Available' : 'Coming soon'} |" }.join("\n")}
  MD

  members.each_with_index do |s, i|
    sidebar = s["sidebar"]
    route = s["route"]
    open_it = []
    if sidebar
      open_it << "In the sidebar, under **#{SECTION_TITLES.fetch(sidebar['section'])}**, choose **#{sidebar['label']}**."
      open_it << "Or press **#{shortcut_glyphs(sidebar['shortcut'])}** (Go menu)." if sidebar["shortcut"]
    end
    if route.start_with?("/")
      open_it << "Link: `substratal://#{route.delete_prefix('/')}` opens it in the app; " \
                 "`https://dashboard.substratalapps.com#{route}` opens it in the web Hub or, once Universal Links are set up, in the app."
    end
    notes_file = File.join(HELP, "_screen-notes", "#{s['id']}.md")
    notes = File.exist?(notes_file) ? File.read(notes_file).strip : nil
    status = built.include?(s["id"]) ? "Available in this version." : "Coming soon: specified, not built yet. The app shows a placeholder with a link back here."

    File.write(File.join(dir, "#{s['id'].downcase}.md"), <<~MD)
      ---
      layout: default
      title: #{yaml_string("#{s['id']} #{s['title']}")}
      parent: #{yaml_string(name)}
      grand_parent: Screen Reference
      nav_order: #{i + 1}
      permalink: /screens/#{s['id'].downcase}/
      ---

      # #{s['title']}
      {: .no_toc }

      #{s['purpose']}
      {: .fs-6 .fw-300 }

      | | |
      |---|---|
      | Screen ID | `#{s['id']}` |
      | Area | #{name} (#{code}) |
      | Who can use it | #{s['audience'] || '—'} |
      | Layout | #{s['archetype']} |
      | Phase | #{s['phase']} |
      | Route | `#{route}` |
      | Status | #{status} |

      #{open_it.empty? ? '' : "## How to open it\n\n#{open_it.map { |l| "- #{l}" }.join("\n")}\n"}
      #{notes ? "## Using this screen\n\n#{notes}\n" : ''}
      ## See also

      - [#{name}](#{'{{'} '/screens/#{slug(domain)}/' | relative_url #{'}}'}): every screen in this area
      - [Screen specification](https://compositecode.github.io/substratalapps-applications-specs/spec/macos/SCREENS.html): controls, data and API calls, for the people building it
    MD
  end
end

# ── Release notes ───────────────────────────────────────────────────────────
changelog = File.read(File.join(ROOT, "CHANGELOG.md")).sub(/\A# .*\n/, "")
File.write(File.join(HELP, "release-notes.md"), <<~MD)
  ---
  layout: default
  title: Release Notes
  nav_order: 90
  permalink: /release-notes/
  ---

  # Release Notes
  {: .no_toc }

  What changed in each version of Substratal Hub for macOS. Generated from
  [`CHANGELOG.md`](https://github.com/CompositeCode/substratalapps-macos/blob/main/CHANGELOG.md).
  {: .fs-6 .fw-300 }

  #{changelog}
MD

puts "help-generate: #{screens.size} screen pages (#{built.size} built) in #{domains.size} areas; " \
     "API #{build['api_spec_version']} (Substratal-Version #{build['api_header_versions'].join(', ')}, #{operations} operations); " \
     "app #{build['app_version']}"
